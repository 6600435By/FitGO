'use client';

import type { MembershipDataQuality } from '@fitgo/shared-types';
import type { ReactNode } from 'react';
import { cov } from './format';

export function MethodModal({
  quality,
  onClose,
}: {
  quality: MembershipDataQuality;
  onClose: () => void;
}) {
  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4">
      <div className="card max-h-[88vh] w-full max-w-2xl space-y-4 overflow-y-auto">
        <div className="flex items-start justify-between gap-2">
          <h3 className="font-semibold">Методика расчёта</h3>
          <button
            type="button"
            className="btn-secondary text-xs"
            onClick={onClose}
          >
            Закрыть
          </button>
        </div>

        <Block title="1. Что считаем">
          <li>
            <b>Экземпляр</b> = одна продажа абонемента клиенту (sale-first:
            берём продажу membership из 1С, затем привязываем документ членства
            и визиты). Экземпляры группируются по SKU (карточке абонемента) и
            по типу/группе.
          </li>
          <li>
            Цена — фактическая оплата по продаже; если продажа не найдена —
            медиана по SKU (помечается «~»). Прайс — из каталога 1С либо
            override в карточке. Скидка = прайс − оплата.
          </li>
          <li>
            Базис «Завершённые» — полный факт по истёкшим абонементам.
            «Активные» — прогноз по текущему темпу посещений.
          </li>
        </Block>

        <Block title="2. Разложение цены">
          <li>
            Из оплаты вычитаются обещанные услуги по карточке: ЛС (кредит),
            массажи, солярий — по прайсу. Остаток = «доступ», он делится между
            ГП и залом пропорционально визитам.
          </li>
          <li>
            Что обещано / использовано / сгорело — по квотам карточки и
            фактическим использованиям; ЛС сгорает в конце срока.
          </li>
        </Block>

        <Block title="3. Полный стек затрат">
          <li>
            Маржа = оплата − (комиссия с продаж + эквайринг + налог + тренеры ГП
            + ПТ-подарки + массаж + анализ состава + солярий + себестоимость
            потраченного ЛС + накладные на визит [+ фикс. накладные на
            участника × мес.]).
          </li>
          <li>
            Комиссия с продаж — override из настроек или сумма средних % админа
            и менеджера из ЗП-профилей. Эквайринг и налог — % от оплаты.
          </li>
          <li>
            Себестоимость массажа / анализа / ПТ — из настроек, иначе из ставок
            ЗП (подсказки «из ЗП»). Себестоимость ЛС = доля COGS × потрачено.
          </li>
        </Block>

        <Block title="4. Тренер ГП: доля и маржинальный метод">
          <li>
            <b>Тренер на посетителя</b> = начисление за занятие / число
            посетивших (ставки FitGO с учётом effectiveFrom). Если фактической
            ставки нет — оценка (показана доля «оценено»).
          </li>
          <li>
            <b>share</b> — стоимость визита ГП = доля «доступа», приходящаяся на
            ГП, / число визитов ГП. Показывает «справедливую» себестоимость
            визита.
          </li>
          <li>
            <b>marginal</b> — визит ГП стоит ровно столько, сколько
            доплачивается тренеру за дополнительного участника; полезно для
            решений «пускать ли ещё людей в группу».
          </li>
        </Block>

        <Block title="5. Сценарии">
          <li>
            <b>Факт</b> — реальные визиты и использования. <b>Норма</b> — визиты
            по норме (визитов/нед.) и полное использование квот. <b>Полный</b>{' '}
            — все услуги из состава использованы полностью.{' '}
            <b>С фикс. накладными</b> — добавляется доля постоянных расходов.
          </li>
          <li>
            Для каждого сценария считаются маржа, цена безубыточности и
            максимум ГП-визитов в месяц до убытка.
          </li>
        </Block>

        <Block title="6. Цена безубыточности (BE)">
          <li>
            BE цена = фиксированные переменные затраты / (1 − (комиссия % +
            эквайринг % + налог %) / 100). Процентные статьи зависят от цены,
            поэтому делим на остаток после них.
          </li>
          <li>
            Макс. скидка = (прайс − BE цена) / прайс. Макс. ГП/мес = (оплата −
            остальные затраты) / тренер за визит / срок в месяцах. Порог BE по
            визитам считается за срок, а не за месяц.
          </li>
        </Block>

        <Block title="7. Сегменты клиентов">
          <li>
            Индекс = визитов ГП в неделю / норма. Сегменты: максимум, норма,
            недогруз — по порогам из настроек; «спящий» — нет визитов дольше
            заданного числа дней.
          </li>
          <li>
            Зал ≈ день визита без ГП/спа в тот же день (приближение).
          </li>
        </Block>

        <div className="rounded-lg bg-slate-800/50 p-3 text-xs text-slate-400">
          Покрытие данных: документы членства {cov(quality.packageDocCoverage)},
          продажи {cov(quality.saleMatchCoverage)}, ЛС{' '}
          {cov(quality.personalAccountCoverage)}, скидки{' '}
          {cov(quality.discountMatchCoverage)}, ставки тренеров ГП{' '}
          {cov(quality.gpTrainerRateCoverage)}. Карточек на проверку:{' '}
          {quality.profilesNeedingReview}.
          {quality.warning && (
            <p className="mt-1 text-amber-300">{quality.warning}</p>
          )}
        </div>
      </div>
    </div>
  );
}

function Block({
  title,
  children,
}: {
  title: string;
  children: ReactNode;
}) {
  return (
    <div>
      <h4 className="mb-1 text-sm font-semibold text-slate-200">{title}</h4>
      <ul className="list-disc space-y-1.5 pl-4 text-sm text-slate-300">
        {children}
      </ul>
    </div>
  );
}
